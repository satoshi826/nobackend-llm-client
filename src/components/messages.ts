/** Split a template around one {placeholder} (for text that wraps a link or button) */
export function around(template: string, name: string): [string, string] {
  const i = template.indexOf(`{${name}}`);
  return i < 0 ? [template, ''] : [template.slice(0, i), template.slice(i + name.length + 2)];
}

/** Join whole sentences the way the language does (a space in English, nothing in Japanese and Chinese) */
export function sentences(...xs: (string | false | null | undefined)[]): string {
  return xs.filter(Boolean).join(getLang() === 'en' ? ' ' : '');
}
